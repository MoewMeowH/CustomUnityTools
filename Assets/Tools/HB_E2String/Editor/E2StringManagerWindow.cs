        private static bool DeclaresAttributeClass(string text)
        {
            if (string.IsNullOrEmpty(text) || text.IndexOf("E2StringAttribute", StringComparison.Ordinal) < 0) return false;
            return s_AttributeClassRegex.IsMatch(StripNonCode(text));
        }

        /// <summary>
        /// 지정한 경로에 E2StringAttribute 스크립트를 생성합니다. overwritePath를 주면 그 파일을 같은 자리에 다시 생성합니다.
        /// </summary>
        private void CreateAttributeScript(string overwritePath = null)
        {
            string requestedFolder = overwritePath != null
                ? Path.GetDirectoryName(overwritePath)
                : string.IsNullOrWhiteSpace(m_TargetFolderPath) ? DEFAULT_TARGET_FOLDER : m_TargetFolderPath;
            if (!TryToAssetsRelativePath(requestedFolder, out string folderPath))
            {
                EditorUtility.DisplayDialog("E2String Manager",
                    $"생성 폴더는 프로젝트의 Assets 폴더 안이어야 합니다.\n\n입력값: {requestedFolder}", "확인");
                return;
            }
            string fileName = overwritePath != null ? Path.GetFileName(overwritePath) : ATTRIBUTE_FILE_NAME;
            if (overwritePath != null && !IsGeneratedAttributeFile(overwritePath, out _))
            {
                EditorUtility.DisplayDialog("E2String Manager",
                    $"매니저가 만든 파일이 아니라서 덮어쓰지 않습니다.\n\n경로: {overwritePath}", "확인");
                return;
            }

            string ns = m_UseGlobalNamespace ? COMPAT_NAMESPACE : (m_CustomNamespace ?? string.Empty).Trim();
            if (!string.IsNullOrEmpty(ns) && (!s_NamespaceNameRegex.IsMatch(ns) || Array.Exists(ns.Split('.'), s_CSharpKeywords.Contains)))
            {
                EditorUtility.DisplayDialog("E2String Manager", $"올바르지 않은 네임스페이스 이름입니다: {ns}", "확인");
                return;
            }

            string filePath = $"{folderPath}/{fileName}";
            if (File.Exists(filePath) &&
                !EditorUtility.DisplayDialog("E2String Manager", $"이미 파일이 존재합니다. 덮어쓸까요?\n\n경로: {filePath}", "덮어쓰기", "취소"))
            {
                return;
            }

            // 글로벌 옵션: 글로벌 + EString.Script 둘 다 생성 / 커스텀: 지정 네임스페이스만 (비우면 글로벌만)
            bool includeGlobal = m_UseGlobalNamespace || string.IsNullOrEmpty(ns);
            string source = BuildAttributeSource(includeGlobal, ns);

            // 폴더가 이미 asmdef에 속하면 그 어셈블리를 쓰고, 아니면 전용 asmdef를 같이 만든다
            string asmdefPath = null;
            string asmdefNote;
            string owningAsmdef = FindOwningAssemblyDefinition(folderPath);
            if (owningAsmdef != null)
            {
                asmdefNote = $"폴더가 이미 어셈블리 정의에 속해 있어 asmdef를 만들지 않았습니다.\n어셈블리 정의: {owningAsmdef}";
            }
            else if (AssemblyDefinitionExists(ATTRIBUTE_ASMDEF_NAME))
            {
                asmdefNote = $"'{ATTRIBUTE_ASMDEF_NAME}' asmdef가 프로젝트에 이미 있어 만들지 않았습니다. 어트리뷰트는 Assembly-CSharp에 들어가므로 asmdef 어셈블리에서는 쓸 수 없습니다.";
            }
            else
            {
                // 다른 스크립트가 있는 폴더에 asmdef를 만들면 그 스크립트까지 새 어셈블리로 옮겨진다.
                // Editor 폴더 규칙이 사라져 에디터 스크립트가 런타임 어셈블리에 들어가는 등(플레이어 빌드 실패) 위험하므로 만들지 않는다.
                int movedScripts = CountScriptsMovedByNewAsmdef(folderPath, filePath);
                if (movedScripts == 0)
                {
                    asmdefPath = $"{folderPath}/{ATTRIBUTE_ASMDEF_NAME}.asmdef";
                    asmdefNote = $"asmdef를 함께 만들었습니다: {asmdefPath}\nasmdef 어셈블리에서 쓰려면 references에 '{ATTRIBUTE_ASMDEF_NAME}'를 추가하세요.";
                }
                else
                {
                    asmdefNote = $"폴더 아래 다른 스크립트 {movedScripts}개가 있어 asmdef를 만들지 않았습니다 (그 스크립트까지 새 어셈블리로 옮겨지므로).\n" +
                                 "어트리뷰트는 Assembly-CSharp에 들어가 asmdef 어셈블리에서는 쓸 수 없습니다. asmdef에서도 쓰려면 다른 스크립트가 없는 전용 폴더에 만드세요.";
                }
            }

            // asmdef를 먼저 쓴다: 어트리뷰트만 써지고 asmdef가 실패하면 어트리뷰트가 Assembly-CSharp에 들어가 버리므로.
            // 어트리뷰트 쓰기가 실패하면 이번에 만든 asmdef를 지워 반쪽 상태를 남기지 않는다.
            bool asmdefWritten = false;
            try
            {
                Directory.CreateDirectory(folderPath);
                if (asmdefPath != null)
                {
                    File.WriteAllText(asmdefPath, BuildAttributeAsmdef(), new UTF8Encoding(false));
                    asmdefWritten = true;
                }
                File.WriteAllText(filePath, source, new UTF8Encoding(true));
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException)
            {
                if (asmdefWritten)
                {
                    try { File.Delete(asmdefPath); }
                    catch (Exception deleteError) when (deleteError is IOException || deleteError is UnauthorizedAccessException) { }
                }
                EditorUtility.DisplayDialog("E2String Manager", $"스크립트 생성에 실패했습니다.\n\n{e.Message}", "확인");
                return;
            }

            AssetDatabase.Refresh();

            m_TargetFolderPath = folderPath;
            EditorPrefs.SetString(PREFS_TARGET_FOLDER_KEY, folderPath);
            EditorUtility.DisplayDialog("E2String Manager", $"E2StringAttribute 스크립트가 성공적으로 생성되었습니다!\n\n경로: {filePath}\n\n{asmdefNote}", "확인");

            RefreshAll();
        }

        private static string BuildAttributeSource(bool includeGlobal, string ns)
        {
            // E2StringOptions는 한 곳에만 정의한다. 글로벌과 네임스페이스 어트리뷰트가 같은 옵션 타입을 써야
            // [EString.Script.E2String(E2StringOptions.All)] 처럼 섞어 써도 타입이 어긋나지 않는다.
            string optionsType = includeGlobal ? "global::E2StringOptions" : "E2StringOptions";

            var sb = new StringBuilder();
            sb.AppendLine(GENERATED_HEADER);
            sb.AppendLine("using System;");

            if (includeGlobal)
            {
                sb.AppendLine();
                AppendOptionsEnum(sb, string.Empty);
                sb.AppendLine();
                AppendAttributeClass(sb, string.Empty, optionsType);
            }

            if (!string.IsNullOrEmpty(ns))
            {
                sb.AppendLine();
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
                if (!includeGlobal)
                {
                    AppendOptionsEnum(sb, "    ");
                    sb.AppendLine();
                }
                AppendAttributeClass(sb, "    ", optionsType);
                sb.AppendLine("}");
            }

            return sb.ToString();
        }

        /// <summary>
        /// 생성기(EString.dll)가 읽는 옵션 비트. 값은 생성기 쪽 상수(OptionIntConversion = 1 &lt;&lt; 1, OptionCollections = 1 &lt;&lt; 2)와 같아야 한다.
        /// 1 &lt;&lt; 0은 비워 둔 자리다 — 다시 매기면 이미 만든 어트리뷰트 파일 · 생성기와 어긋난다.
        /// </summary>
        private static void AppendOptionsEnum(StringBuilder sb, string indent)
        {
            sb.AppendLine($"{indent}[Flags]");
            sb.AppendLine($"{indent}public enum E2StringOptions");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{indent}    /// <summary>ToStringFast, To{{Enum}}Fast(string) — 항상 생성</summary>");
            sb.AppendLine($"{indent}    ParseExact = 0,");
            sb.AppendLine($"{indent}    /// <summary>ToIntFast, To{{Enum}}Fast(int), IsDefinedFast (+ [Flags]면 IsValidFlagsFast)</summary>");
            sb.AppendLine($"{indent}    IntConversion = 1 << 1,");
            sb.AppendLine($"{indent}    /// <summary>Values</summary>");
            sb.AppendLine($"{indent}    Collections = 1 << 2,");
            sb.AppendLine($"{indent}    All = ~0,");
            sb.AppendLine($"{indent}}}");
        }

        private static void AppendAttributeClass(StringBuilder sb, string indent, string optionsType)
        {
            sb.AppendLine($"{indent}[AttributeUsage(AttributeTargets.Enum, Inherited = false, AllowMultiple = false)]");
            sb.AppendLine($"{indent}public sealed class E2StringAttribute : Attribute");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{indent}    public E2StringAttribute({optionsType} options = {optionsType}.ParseExact) {{ Options = options; }}");
            sb.AppendLine($"{indent}    public {optionsType} Options {{ get; }}");
            sb.AppendLine($"{indent}}}");
        }

