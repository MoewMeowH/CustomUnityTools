        /// <summary>
        /// 프로젝트 내에 E2StringAttribute 정의가 있는지 검사합니다.
        /// </summary>
        private void CheckAttributeInstallation()
        {
            m_IsAttributeInstalled = false;
            m_InstalledAttributePath = string.Empty;
            m_InstalledAttributeAssembly = string.Empty;
            m_InstalledAttributeIsGenerated = false;

            // 1. 파일명으로 후보를 찾고 실제 클래스 선언이 있는지 확인 (패키지 포함)
            foreach (string guid in AssetDatabase.FindAssets("E2StringAttribute t:MonoScript"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                var monoScript = AssetDatabase.LoadAssetAtPath<MonoScript>(path);
                if (monoScript != null && DeclaresAttributeClass(monoScript.text))
                {
                    SetInstalledAttribute(path);
                    return;
                }
            }

            // 2. 파일명이 다른 경우 대비: Assets 하위 전체 .cs 검색 (에디터 전용 제외)
            foreach (string path in EnumerateProjectScripts())
            {
                if (path.Contains("/Editor/")) continue;
                if (!TryReadText(path, out string text)) continue;

                if (DeclaresAttributeClass(text))
                {
                    SetInstalledAttribute(path);
                    return;
                }
            }
        }

        private void SetInstalledAttribute(string path)
        {
            m_InstalledAttributePath = path;
            m_IsAttributeInstalled = true;

            // 반환값에 ".dll"이 붙는지 문서에 없으므로 붙어 있으면 뗀다. 어셈블리 이름에 '.'이 들어가므로 GetFileNameWithoutExtension은 쓰지 않는다.
            string assemblyName = CompilationPipeline.GetAssemblyNameFromScriptPath(path) ?? string.Empty;
            if (assemblyName.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
            {
                assemblyName = assemblyName.Substring(0, assemblyName.Length - 4);
            }
            m_InstalledAttributeAssembly = assemblyName;

            m_InstalledAttributeIsGenerated = IsGeneratedAttributeFile(path, out string generatedText);
            if (m_InstalledAttributeIsGenerated)
            {
                LoadNamespaceOptionsFrom(generatedText);
            }
        }

        private static bool IsGeneratedAttributeFile(string path, out string text)
        {
            if (!TryReadText(path, out text) || text == null) return false;
            return text.TrimStart('﻿').StartsWith(GENERATED_HEADER, StringComparison.Ordinal);
        }

        /// <summary>
        /// 기존 생성 파일의 네임스페이스 구성을 다시 생성 옵션의 기본값으로 채웁니다 (기본값으로 덮어써 사용자 코드가 깨지지 않도록).
        /// BuildAttributeSource의 역: 글로벌 + EString.Script = 호환 옵션, 그 밖은 커스텀(네임스페이스 없으면 글로벌만).
        /// </summary>
        private void LoadNamespaceOptionsFrom(string text)
        {
            string code = StripNonCode(text);
            Match nsMatch = s_FileNamespaceRegex.Match(code);
            string ns = nsMatch.Success ? nsMatch.Groups["ns"].Value : string.Empty;
            bool hasGlobal = s_GlobalAttributeClassRegex.IsMatch(code);

            if (hasGlobal && string.Equals(ns, COMPAT_NAMESPACE, StringComparison.Ordinal))
            {
                m_UseGlobalNamespace = true;
                m_CustomNamespace = COMPAT_NAMESPACE;
            }
            else
            {
                m_UseGlobalNamespace = false;
                m_CustomNamespace = ns;
            }
        }

        /// <summary>Assembly-CSharp(-firstpass) 같은 기본 어셈블리인지. asmdef 어셈블리는 이 어셈블리를 참조할 수 없다.</summary>
        private static bool IsPredefinedAssembly(string assemblyName)
        {
            return assemblyName.StartsWith("Assembly-CSharp", StringComparison.Ordinal);
        }

        /// <summary>
        /// 폴더가 속한 asmdef/asmref 파일 경로를 찾습니다 (폴더부터 Assets까지 올라가며 검색). 없으면 null.
        /// </summary>
        private static string FindOwningAssemblyDefinition(string assetFolder)
        {
            for (string dir = assetFolder; !string.IsNullOrEmpty(dir); dir = Path.GetDirectoryName(dir)?.Replace('\\', '/'))
            {
                if (Directory.Exists(dir))
                {
                    foreach (string pattern in new[] { "*.asmdef", "*.asmref" })
                    {
                        string[] found = Directory.GetFiles(dir, pattern, SearchOption.TopDirectoryOnly);
                        if (found.Length > 0) return found[0].Replace('\\', '/');
                    }
                }

                if (string.Equals(dir, "Assets", StringComparison.Ordinal)) break;
            }
            return null;
        }

        /// <summary>폴더에 asmdef를 만들면 새 어셈블리로 함께 옮겨질 다른 스크립트 수 (하위 asmdef에 속한 스크립트 제외).</summary>
        private static int CountScriptsMovedByNewAsmdef(string assetFolder, string excludePath)
        {
            if (!Directory.Exists(assetFolder)) return 0;

            int count = 0;
            foreach (string file in Directory.EnumerateFiles(assetFolder, "*.cs", SearchOption.AllDirectories))
            {
                string path = file.Replace('\\', '/');
                if (string.Equals(path, excludePath, StringComparison.OrdinalIgnoreCase) || IsIgnoredByUnity(path)) continue;
                if (FindOwningAssemblyDefinition(Path.GetDirectoryName(path)?.Replace('\\', '/')) != null) continue;
                count++;
            }
            return count;
        }

