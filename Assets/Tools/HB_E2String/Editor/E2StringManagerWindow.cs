        /// <summary>파일명이 아니라 asmdef 안의 "name"으로 같은 어셈블리가 있는지 봅니다 (파일명과 이름은 다를 수 있음).</summary>
        private static bool AssemblyDefinitionExists(string assemblyName)
        {
            foreach (string guid in AssetDatabase.FindAssets("t:AssemblyDefinitionAsset"))
            {
                var asset = AssetDatabase.LoadAssetAtPath<TextAsset>(AssetDatabase.GUIDToAssetPath(guid));
                if (asset == null) continue;

                AsmdefNameOnly parsed;
                try
                {
                    parsed = JsonUtility.FromJson<AsmdefNameOnly>(asset.text);
                }
                catch (ArgumentException)
                {
                    continue;
                }

                if (parsed != null && string.Equals(parsed.name, assemblyName, StringComparison.Ordinal)) return true;
            }
            return false;
        }

